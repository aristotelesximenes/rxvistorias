function openNormPicker(item){if(S.active.completed||item.status!=='issue')return;normPickerState.itemId=item.id;$('#norm-service').innerHTML='<option value="">Todos os serviços</option>'+Object.entries(normServices).map(([key,label])=>`<option value="${key}">${label}</option>`).join('');$('#norm-topic').innerHTML='<option value="">Todos os temas</option>'+Object.entries(normTopics).map(([key,label])=>`<option value="${key}">${label}</option>`).join('');$('#norm-service').value=normServiceFor(item);$('#norm-topic').value=normTopicFor(item);$('#norm-search').value='';if(!filteredNorms().length)$('#norm-topic').value='';$('#norm-item-context').textContent=S.active.rooms.find(room=>room.items.some(i=>i.id===item.id)).name+' · '+item.title;renderNormPicker();$('#norm-results').scrollTop=0;$('#norm-dialog').showModal();}
function chooseCatalogNorm(id){const item=findItem(normPickerState.itemId),norm=NORM_CATALOG.find(n=>n.id===id);if(!norm||S.active.completed||item.status!=='issue')return;item.normativeReferences??=[];if(item.normativeReferences.length>=10||item.normativeReferences.some(ref=>ref.catalogId===id))return;item.normativeReferences.push({standard:norm.code+' — '+norm.title,edition:norm.edition,clause:'',justification:'',catalogId:norm.id,summary:norm.summary,source:norm.source});changed();renderActive();renderNormPicker();$('#norm-dialog .dialog-footer button')?.focus({preventScroll:true});}
